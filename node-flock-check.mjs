// temp (not committed): node harness for the flock in level mode against the stub farm
import * as THREE from 'three';
import { createSim } from './src/sim.js';
import { createEvents, EV } from './src/events.js';
import { createFarm } from './src/farm.js';
import { createInteract } from './src/interact.js';
import { buildProps } from './src/props.js';
import { createFlock } from './src/flock.js';
const env = createSim();
const events = createEvents();
const farm = createFarm(env, { events });
const scene = new THREE.Scene();
const camera = new THREE.PerspectiveCamera(40, 1.6, 0.1, 600);
camera.position.set(-10, 25, 25); camera.lookAt(-10, 0, 0); camera.updateMatrixWorld();
const ctx = { THREE, scene, camera, env, events, farm, interact: createInteract([]) };
ctx.props = buildProps(ctx, {});
const player = { position: new THREE.Vector3(-10, 0, 20), isInside: false, carry() {} };
ctx.player = player;
ctx.level = { sampling: null };
const flock = createFlock(ctx, {});
ctx.flock = flock;
const log = [];
events.on('*', (p, t) => { if (['carry', 'bird:pick', 'bird:release', 'dead:pick'].includes(t)) log.push(t + ' ' + JSON.stringify(p)); });
const step = (sec, dt = 1 / 30) => { for (let i = 0; i < sec / dt; i++) { env.update(dt); flock.update(dt, env, player.position); } };
export { env, events, farm, flock, ctx, player, step, log, EV };
